import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import * as T from 'three';

const url = process.argv[2];
if (!url) throw new Error('Pass the actual preview URL');
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
const issues = [], requests = [], report = {};
try {
  const context = await browser.newContext({ viewport: { width: 960, height: 720 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  page.on('pageerror', e => issues.push(e.message));
  page.on('requestfailed', r => issues.push(`${r.url()}: ${r.failure()?.errorText}`));
  page.on('request', r => requests.push(r.url()));
  await page.goto(url);
  await expect(page.getByRole('heading', { name: 'ТИШЕ. ЧЕЛОВЕК!' })).toBeVisible();
  await page.getByRole('button', { name: 'Начать вылазку', exact: true }).click();
  await page.getByRole('button', { name: 'Я готов', exact: true }).click();
  await expect(page.locator('#hud')).toBeVisible();
  if (await page.evaluate(() => '__gameQA' in window)) throw new Error('Diagnostics leaked into production');
  const camera = new T.OrthographicCamera(-15.5, 15.5, 11.625, -11.625, 0.1, 120);
  camera.position.set(Math.sin(-0.12) * 25, 29, -0.4 + Math.cos(-0.12) * 25); camera.lookAt(0, 0, -0.4); camera.updateMatrixWorld();
  const baby = new T.Vector3(-8.3, 0, 1.8).project(camera);
  await page.mouse.click((baby.x + 1) * 480, (-baby.y + 1) * 360);
  await expect(page.locator('#family')).toHaveText('1 / 6', { timeout: 25000 });
  report.production = { html: true, diagnosticsAbsent: true, realRescue: true, externalRequests: requests.filter(u => !u.startsWith(url)) };
  await page.reload();
  await page.getByRole('button', { name: 'Начать вылазку', exact: true }).click();
  await page.keyboard.press('Space');
  await expect(page.locator('#silk')).toContainText('2 / 3');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('heading', { name: 'Можно выдохнуть' })).toBeVisible();
  report.production.web = true; report.production.pause = true;
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/production-pause.png' });
  await context.close();
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const phone = await mobile.newPage(); phone.on('pageerror', e => issues.push(e.message));
  await phone.goto(url); await phone.getByRole('button', { name: 'Начать вылазку', exact: true }).click(); await phone.getByRole('button', { name: 'Я готов', exact: true }).click();
  await expect(phone.getByRole('button', { name: 'Джойстик движения' })).toBeVisible();
  await expect(phone.getByRole('button', { name: 'Паутина', exact: true })).toBeVisible();
  if (await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile overflow');
  await phone.screenshot({ path: 'artifacts/production-mobile.png' });
  report.mobile = { viewport: '390x844', joystick: true, web: true, noOverflow: true };
  await mobile.close();
  if (issues.length || report.production.externalRequests.length) throw new Error(JSON.stringify({ issues, requests }));
  report.issues = issues;
  await writeFile('artifacts/production-report.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
